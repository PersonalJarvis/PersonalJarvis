"""Retained WebRTC-offer compatibility seam for realtime plugins.

Some externally authenticated realtime transports need a genuine browser SDP
offer even when the microphone owner is the native desktop voice loop.  The UI
keeps a recv-only peer ready and registers its offer here; a provider leases it
exactly once and returns the answer through the same registration.  No audio,
credentials, or model content passes through this broker.

No built-in provider currently declares ``requires_webrtc_offer = True``:
Codex owns its media peer in-process and the API providers use their SDKs. The
broker, websocket, and frontend component intentionally remain capability-
gated for third-party entry-point providers that need browser-origin WebRTC.
They are compatibility infrastructure, not an alternate Codex media path.
"""

from __future__ import annotations

import asyncio
import time
from collections import deque
from dataclasses import dataclass
from typing import Literal

_MAX_SDP_CHARS = 256_000
_MAX_OFFER_ID_CHARS = 128
_DEFAULT_OFFER_TTL_S = 20.0
_DEFAULT_MAX_OFFERS = 32
_DEFAULT_MAX_OFFERS_PER_OWNER = 2


def validate_webrtc_offer_sdp(offer_sdp: object) -> str:
    """Validate one browser WebRTC offer at every ingress boundary."""
    if not isinstance(offer_sdp, str):
        raise ValueError("WebRTC offer SDP must be text")
    normalized = offer_sdp.strip()
    if not normalized or len(normalized) > _MAX_SDP_CHARS:
        raise ValueError("WebRTC offer SDP is empty or too large")
    if not normalized.startswith("v=0"):
        raise ValueError("WebRTC offer SDP must be generated by RTCPeerConnection")
    return normalized


@dataclass(frozen=True, slots=True)
class TransportOfferResult:
    """One terminal result delivered to the UI registration."""

    type: Literal["answer", "release"]
    offer_id: str
    answer_sdp: str = ""


@dataclass(slots=True)
class _OfferEntry:
    offer_id: str
    offer_sdp: str
    created_at: float
    results: asyncio.Queue[TransportOfferResult]
    owner_id: str = "anonymous"
    claimed: bool = False
    answered: bool = False


class TransportOfferRegistration:
    """UI-owned handle for one registered offer."""

    def __init__(self, broker: RealtimeTransportOfferBroker, entry: _OfferEntry) -> None:
        self._broker = broker
        self._entry = entry

    @property
    def offer_id(self) -> str:
        return self._entry.offer_id

    async def wait(self) -> TransportOfferResult:
        return await self._entry.results.get()

    async def cancel(self) -> None:
        await self._broker.cancel(self._entry.offer_id)


class TransportOfferLease:
    """Provider-owned single-use lease of a genuine browser SDP offer."""

    def __init__(self, broker: RealtimeTransportOfferBroker, entry: _OfferEntry) -> None:
        self._broker = broker
        self._entry = entry

    @property
    def offer_id(self) -> str:
        return self._entry.offer_id

    @property
    def offer_sdp(self) -> str:
        return self._entry.offer_sdp

    async def answer(self, answer_sdp: str) -> bool:
        """Deliver an answer, returning false if the UI disconnected first."""
        return await self._broker.answer(self._entry.offer_id, answer_sdp)

    async def release(self) -> None:
        """Return an unusable/abandoned lease so the UI creates a fresh offer."""
        await self._broker.release(self._entry.offer_id)


class RealtimeTransportOfferBroker:
    """Concurrency-safe one-shot offer queue shared inside the web process."""

    def __init__(
        self,
        *,
        offer_ttl_s: float = _DEFAULT_OFFER_TTL_S,
        max_offers: int = _DEFAULT_MAX_OFFERS,
        max_offers_per_owner: int = _DEFAULT_MAX_OFFERS_PER_OWNER,
    ) -> None:
        self._lock = asyncio.Lock()
        self._available = asyncio.Event()
        self._entries: dict[str, _OfferEntry] = {}
        self._pending: deque[str] = deque()
        self._offer_ttl_s = max(0.1, float(offer_ttl_s))
        self._max_offers = max(1, int(max_offers))
        self._max_offers_per_owner = max(1, int(max_offers_per_owner))

    def _sync_available_locked(self) -> None:
        if self._pending:
            self._available.set()
        else:
            self._available.clear()

    def _remove_pending_locked(self, offer_id: str) -> None:
        if offer_id in self._pending:
            self._pending = deque(
                pending_id
                for pending_id in self._pending
                if pending_id != offer_id
            )

    def _release_entry_locked(self, offer_id: str) -> None:
        entry = self._entries.pop(offer_id, None)
        self._remove_pending_locked(offer_id)
        if entry is not None and not entry.results.full():
            entry.results.put_nowait(
                TransportOfferResult(type="release", offer_id=entry.offer_id)
            )
        self._sync_available_locked()

    def _sweep_stale_locked(self, now: float) -> None:
        expired = [
            offer_id
            for offer_id, entry in self._entries.items()
            if not entry.claimed and now - entry.created_at >= self._offer_ttl_s
        ]
        for offer_id in expired:
            self._release_entry_locked(offer_id)

    async def register(
        self,
        offer_id: str,
        offer_sdp: str,
        *,
        owner_id: str = "anonymous",
    ) -> TransportOfferRegistration:
        normalized_id = str(offer_id or "").strip()
        normalized_sdp = validate_webrtc_offer_sdp(offer_sdp)
        normalized_owner = str(owner_id or "anonymous").strip() or "anonymous"
        if not normalized_id or len(normalized_id) > _MAX_OFFER_ID_CHARS:
            raise ValueError("offer_id must contain 1 to 128 characters")
        async with self._lock:
            now = time.monotonic()
            self._sweep_stale_locked(now)
            if normalized_id in self._entries:
                raise ValueError("offer_id is already registered")
            if len(self._entries) >= self._max_offers:
                raise ValueError("too many WebRTC offers are already pending")
            owner_count = sum(
                1
                for entry in self._entries.values()
                if entry.owner_id == normalized_owner
            )
            if owner_count >= self._max_offers_per_owner:
                raise ValueError("too many WebRTC offers are pending for this client")
            entry = _OfferEntry(
                offer_id=normalized_id,
                offer_sdp=normalized_sdp,
                created_at=now,
                results=asyncio.Queue(maxsize=2),
                owner_id=normalized_owner,
            )
            self._entries[normalized_id] = entry
            self._pending.append(normalized_id)
            self._sync_available_locked()
        return TransportOfferRegistration(self, entry)

    async def acquire(self, *, timeout_s: float = 0.0) -> TransportOfferLease | None:
        """Lease the oldest live offer, optionally waiting for UI readiness."""
        timeout = max(0.0, float(timeout_s))
        deadline = asyncio.get_running_loop().time() + timeout
        while True:
            async with self._lock:
                self._sweep_stale_locked(time.monotonic())
                while self._pending:
                    offer_id = self._pending.popleft()
                    entry = self._entries.get(offer_id)
                    if entry is None or entry.claimed:
                        continue
                    entry.claimed = True
                    self._sync_available_locked()
                    return TransportOfferLease(self, entry)
                self._sync_available_locked()

            remaining = deadline - asyncio.get_running_loop().time()
            if remaining <= 0:
                return None
            try:
                await asyncio.wait_for(self._available.wait(), timeout=remaining)
            except TimeoutError:  # A bounded wait normally reports that no offer became available.
                return None

    async def answer(self, offer_id: str, answer_sdp: str) -> bool:
        normalized_sdp = str(answer_sdp or "").strip()
        if not normalized_sdp or len(normalized_sdp) > _MAX_SDP_CHARS:
            raise ValueError("WebRTC answer SDP is empty or too large")
        async with self._lock:
            entry = self._entries.get(str(offer_id))
            if entry is None or not entry.claimed or entry.answered:
                return False
            entry.answered = True
            entry.results.put_nowait(
                TransportOfferResult(
                    type="answer",
                    offer_id=entry.offer_id,
                    answer_sdp=normalized_sdp,
                )
            )
            return True

    async def release(self, offer_id: str) -> None:
        async with self._lock:
            self._release_entry_locked(str(offer_id))

    async def cancel(self, offer_id: str) -> None:
        """Remove an offer whose owning UI socket disconnected."""
        await self.release(offer_id)

    async def pending_count(self) -> int:
        """Return live unclaimed offers for diagnostics and focused tests."""
        async with self._lock:
            return sum(1 for entry in self._entries.values() if not entry.claimed)


_SHARED_BROKER = RealtimeTransportOfferBroker()


def get_realtime_transport_offer_broker() -> RealtimeTransportOfferBroker:
    """Return the process-local provider/UI handoff broker."""
    return _SHARED_BROKER


