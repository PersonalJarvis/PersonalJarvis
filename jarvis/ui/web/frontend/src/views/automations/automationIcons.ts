export const DEFAULT_AUTOMATION_ICON: LucideIcon = Sparkles;

/** Resolve a lucide kebab-case name; unknown or empty → Sparkles. */
export function templateIcon(name: string | null | undefined): LucideIcon {
  if (!name) return DEFAULT_AUTOMATION_ICON;
  return ICONS[name.trim().toLowerCase()] ?? DEFAULT_AUTOMATION_ICON;
}
